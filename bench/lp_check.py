#!/usr/bin/env python3
"""Numerics gate for a new image / patch set, run through the PD router.

    python3 bench/lp_check.py --url http://localhost:8080 \
        --ref results/raw/k3_lp_v2.txt --out results/numerics_<label>.json

1. First-token top-5 logprobs on the three fixed prompts of bench/lp.sh,
   compared with the validated reference (k3_lp_v1 == k3_lp_v2 byte for byte,
   taken on the 0901 image). In PD the first token comes from the PREFILL
   instance, so this checks the prefill MoE path. A different TP degree or base
   moves the reduction order, so values are compared with a tolerance, but the
   top-1 token must match exactly and the top-5 sets must mostly agree.
2. A 32-token greedy continuation per prompt, generated by the DECODE instance.
   There is no stored reference for it; it is saved so decode arms (tp / dp /
   dcp, SM counts) can be compared with each other -- a patch that fails open
   (e.g. _uses_ep_a2a without deepep_v2) turns these into garbage.

Exit 1 on a top-1 mismatch, a top-5 overlap below --min-overlap, or a top-1
logprob off by more than --tol.

Why --tol is 0.30 and not tighter (measured 2026-10-15 on the sgla6a8c560 image,
fib prompt top-1 logprob; reference -1.517 from the 0901 image):
    new image, TP8, a2a=none   (patched code not on the path)  -1.771  |d|=0.254
    new image, TP8, deepep_v2  (patched)                       -1.604  |d|=0.087
    new image, PD TP16, deepep_v2                              -1.693  |d|=0.176
The UNPATCHED arm drifts furthest, so a new base moves these values by itself
(and none vs v2 differ in activation precision: v2 dispatches FP8). Every arm
kept the same top-1 on all three prompts and 14/15 top-5 sets at 5/5. What
this gate must catch is a patch failing open, which produces garbage, not a
0.2 shift -- so: exact top-1, >=4/5 top-5, |d| <= 0.30.
"""
import argparse
import json
import re
import sys
import urllib.request

PROMPTS = ["The capital of France is", "2 + 2 =", "def fibonacci(n):"]


def load_ref(path):
    ref, cur = {}, None
    for line in open(path):
        m = re.match(r"PROMPT: (.*)$", line.rstrip("\n"))
        if m:
            cur = m.group(1)
            ref[cur] = []
            continue
        m = re.match(r"\s+(.+?)\s+([+-]\d+\.\d+)$", line.rstrip("\n"))
        if m and cur is not None:
            ref[cur].append((eval(m.group(1)), float(m.group(2))))  # repr'd token
    return ref


def post(url, body):
    req = urllib.request.Request(url + "/v1/completions", json.dumps(body).encode(),
                                 {"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=600))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", required=True)
    ap.add_argument("--ref", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--model", default="moonshotai/Kimi-K3")
    ap.add_argument("--tol", type=float, default=0.30)
    ap.add_argument("--min-overlap", type=int, default=4)
    a = ap.parse_args()

    ref = load_ref(a.ref)
    out, bad = {"prompts": {}}, 0
    for p in PROMPTS:
        r = post(a.url, {"model": a.model, "prompt": p, "max_tokens": 1,
                         "temperature": 0, "logprobs": 5})
        lp = (r["choices"][0].get("logprobs") or {}).get("top_logprobs")
        cont = post(a.url, {"model": a.model, "prompt": p, "max_tokens": 32,
                            "temperature": 0})["choices"][0]["text"]
        rec = {"continuation": cont}
        if not lp:
            print(f"WARN  {p!r}: no logprobs returned through the router; top-1 not checked")
        else:
            got = sorted(lp[0].items(), key=lambda kv: -kv[1])
            want = ref[p]
            same_top1 = got[0][0] == want[0][0]
            d_top1 = abs(got[0][1] - want[0][1])
            overlap = len({t for t, _ in got} & {t for t, _ in want})
            ok = same_top1 and d_top1 <= a.tol and overlap >= a.min_overlap
            bad += 0 if ok else 1
            rec.update(top5=got, ref_top5=want, same_top1=same_top1,
                       d_top1=d_top1, top5_overlap=overlap, ok=ok)
            print(f"{'OK  ' if ok else 'FAIL'}  {p!r}: top1 {got[0][0]!r} {got[0][1]:+.4f} "
                  f"(ref {want[0][0]!r} {want[0][1]:+.4f}, |d|={d_top1:.4f}) top5 overlap {overlap}/5")
        print(f"      continuation: {cont!r}")
        out["prompts"][p] = rec
    out["failures"] = bad
    json.dump(out, open(a.out, "w"), indent=1)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
